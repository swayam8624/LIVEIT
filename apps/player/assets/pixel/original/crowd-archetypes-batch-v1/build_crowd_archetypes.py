def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def rect(d: ImageDraw.ImageDraw, box, color) -> None:
    d.rectangle(box, fill=color)


def draw_prop(d: ImageDraw.ImageDraw, role: dict, direction: str, phase: str, y: int, skin) -> None:
    """Draw a role cue with independently authored side/front/back placement."""
    p = role["prop"]
    moving = phase != "idle"
    step = 1 if phase == "walk-a" else -1 if phase == "walk-b" else 0
    if p == "book":
        if direction == "south": rect(d, (3, y + 13, 6, y + 17), role["accent"])
        elif direction == "north": rect(d, (18, y + 13, 21, y + 17), role["accent"])
        elif direction == "west": rect(d, (3, y + 13, 6, y + 16), role["accent"])
        else: rect(d, (18, y + 14, 21, y + 17), role["accent"])
    elif p == "briefcase":
        if direction in ("south", "north"): rect(d, (3 if direction == "south" else 18, y + 18, 6 if direction == "south" else 21, y + 22), role["accent"])
        elif direction == "west": rect(d, (2, y + 17, 5, y + 22), role["accent"])
        else: rect(d, (19, y + 17, 22, y + 22), role["accent"])
    elif p == "tag":
        rect(d, (9, y + 13, 10, y + 15), role["accent"])
        if direction == "west": rect(d, (8, y + 14, 9, y + 16), role["accent"])
        elif direction == "east": rect(d, (14, y + 14, 15, y + 16), role["accent"])
    elif p == "loaf":
        if direction == "south": rect(d, (17, y + 15 + step, 21, y + 18 + step), role["accent"])
        elif direction == "north": rect(d, (3, y + 15 - step, 7, y + 18 - step), role["accent"])
        elif direction == "west": rect(d, (2, y + 14, 6, y + 17), role["accent"])
        else: rect(d, (18, y + 14, 22, y + 17), role["accent"])
    elif p == "helmet":
        if direction == "south": rect(d, (8, y + 1, 15, y + 3), role["accent"])
        elif direction == "north": rect(d, (9, y + 1, 16, y + 3), role["accent"])
        elif direction == "west": rect(d, (5, y + 2, 10, y + 4), role["accent"])
        else: rect(d, (14, y + 2, 19, y + 4), role["accent"])
    elif p == "cap":
        if direction == "south": rect(d, (8, y + 1, 15, y + 3), role["accent"])
        elif direction == "north": rect(d, (9, y + 1, 16, y + 3), role["accent"])
        elif direction == "west": rect(d, (4, y + 2, 9, y + 3), role["accent"])
        else: rect(d, (15, y + 2, 20, y + 3), role["accent"])
    elif p == "keys":
        x = 4 if direction in ("south", "west") else 19
        rect(d, (x, y + 18, x + 1, y + 20), role["accent"])
        rect(d, (x - 1 if x < 10 else x + 1, y + 20, x + 1 if x < 10 else x + 3, y + 20), role["accent"])
    elif p == "radio":
        x = 4 if direction in ("south", "west") else 18
        rect(d, (x, y + 12, x + 2, y + 15), role["accent"])
        rect(d, (x + 1, y + 10, x + 1, y + 11), role["accent"])
    elif p == "tote":
        x = 3 if direction in ("south", "west") else 18
        rect(d, (x, y + 16, x + 3, y + 21), role["accent"])
        rect(d, (x + 1, y + 14, x + 2, y + 16), role["accent"])
    elif p == "instrument":
        if direction == "south":
            rect(d, (16, y + 13, 20, y + 23), role["accent"])
            rect(d, (15, y + 15, 17, y + 16), role["accent"])
        elif direction == "north":
            rect(d, (4, y + 13, 8, y + 23), role["accent"])
